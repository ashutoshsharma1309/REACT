"""Evidence packs (Phase 6).

When a person approves or rejects a decision, REACT writes a JSON evidence pack to the artifact store (local directory
or S3) and records its SHA-256. The pack freezes what the reviewer saw, so the decision can be audited later even
if the live data changes.

Contents: decision, approvals, actions (simulated), investigation conclusion, the cited evidence items with their source
record ids, the impact-engine figures (copied, never recalculated), the VISIBLE agent trace (agent, action, tool,
arguments, evidence ids, state, duration, error, summary; never hidden reasoning) and data provenance.

Failure policy: storage failure never blocks or reverses the approval. The artifact row is kept with status FAILED and a
safe error message, the failure is logged and counted (EvidencePackFailed), and the UI shows it.
"""
from __future__ import annotations

import json
import uuid
from typing import Any

from sqlalchemy import select
from sqlalchemy.orm import Session, selectinload

from app.config import settings
from app.database.base import utcnow
from app.models import AgentRun, Artifact, Decision, EvidenceItem, Investigation, SystemState
from app.observability import get_logger, log_event
from app.observability.metrics import emit
from app.storage import ArtifactStore, StorageError, build_store
from app.version import APP_VERSION

log = get_logger("react.artifacts")
PACK_SCHEMA_VERSION = "1"
TRACE_FIELDS = ("sequence", "timestamp", "agent_name", "event_type", "state", "tool_name", "tool_arguments", "evidence_ids", "hypothesis_ids", "summary", "duration_ms", "status", "error")


def _iso(v: Any) -> Any:
    return v.isoformat() if hasattr(v, "isoformat") else v


def build_evidence_pack(db: Session, decision: Decision, trigger: str) -> dict[str, Any]:
    inv = db.get(Investigation, decision.investigation_id) if decision.investigation_id else None
    run = db.scalar(select(AgentRun).options(selectinload(AgentRun.trace_entries)).where(AgentRun.id == decision.agent_run_id)) if decision.agent_run_id else None
    cited = {str(x) for x in (decision.evidence_ids or []) + (decision.contradicting_evidence_ids or [])}
    items = []
    if inv is not None and cited:
        ids = [uuid.UUID(x) for x in cited if _is_uuid(x)]
        for e in db.scalars(select(EvidenceItem).where(EvidenceItem.id.in_(ids))).all():
            items.append({"id": str(e.id), "signal": e.signal, "claim": e.claim, "source_type": e.source_type, "source_ids": e.source_ids, "timestamp": _iso(e.timestamp), "value": e.value, "unit": e.unit, "baseline_value": e.baseline_value, "supports": e.supports, "contradicts": e.contradicts, "evidence_support_score": e.evidence_support_score})
    state = db.get(SystemState, 1)
    return {
        "schema_version": PACK_SCHEMA_VERSION,
        "kind": "evidence_pack",
        "generated_at": utcnow().isoformat(),
        "trigger": trigger,
        "app": {"name": settings.app_name, "version": APP_VERSION, "environment": settings.app_env},
        "provenance": {
            "data": "SYNTHETIC",
            "note": "Generated by REACT's deterministic synthetic data generator for a fictional manufacturer. Not real business data.",
            "seed": state.seed if state else None,
            "generator_version": state.generator_version if state else None,
            "data_window": {"start": _iso(state.data_start), "end": _iso(state.data_end)} if state else None,
            "money_source": "app/impact/engine.py (deterministic). No monetary figure in this pack was produced by a language model.",
        },
        "decision": {
            "id": str(decision.id), "status": decision.status.value, "readiness": decision.decision_readiness.value, "priority": decision.priority,
            "action_type": decision.action_type, "target_type": decision.target_type, "target_id": decision.target_id, "target_name": decision.target_name,
            "summary": decision.summary, "problem_statement": decision.problem_statement, "recommendation": decision.recommendation, "rationale": decision.rationale,
            "required_actions": decision.required_actions, "alternatives": decision.alternatives, "risks": decision.risks, "assumptions": decision.assumptions,
            "evidence_ids": decision.evidence_ids, "contradicting_evidence_ids": decision.contradicting_evidence_ids,
            "hypothesis_id": str(decision.hypothesis_id) if decision.hypothesis_id else None, "hypothesis_type": decision.hypothesis_type, "evidence_support_score": decision.evidence_support_score,
            "expected_impact": decision.expected_impact, "validation": decision.validation, "timeline": decision.timeline,
            "provider": decision.provider, "llm_used": decision.llm_used, "fallback_used": decision.fallback_used,
        },
        "approvals": [{"id": str(a.id), "status": a.status.value, "reviewed_by": a.reviewed_by, "reviewed_at": _iso(a.reviewed_at), "reason": a.reason} for a in decision.approvals],
        "actions": [{"id": str(a.id), "action_type": a.action_type, "status": a.status.value, "simulated": a.simulated, "target_name": a.target_name, "result": a.result, "transitions": a.transitions} for a in decision.actions],
        "investigation": {"id": str(inv.id), "conclusion": inv.conclusion, "impact": inv.impact} if inv else None,
        "evidence": sorted(items, key=lambda i: i["id"]),
        "agent_run": {"id": str(run.id), "provider": run.provider, "model": run.model, "llm_used": run.llm_used, "fallback_used": run.fallback_used, "tool_calls": run.tool_calls_count, "llm_calls": run.llm_calls_count, "result_status": run.result_status} if run else None,
        "agent_trace": [{k: _iso(getattr(t, k)) for k in TRACE_FIELDS} for t in sorted(run.trace_entries, key=lambda t: t.sequence)] if run else [],
    }


def _is_uuid(x: str) -> bool:
    try:
        uuid.UUID(x)
        return True
    except ValueError:
        return False


def archive_decision(db: Session, decision: Decision, trigger: str, store: ArtifactStore | None = None) -> Artifact:
    """Write the evidence pack. Never raises: failures are recorded on the artifact row."""
    artifact = Artifact(id=uuid.uuid4(), kind="evidence_pack", decision_id=decision.id, trigger=trigger, status="PENDING", storage_backend=settings.storage_backend, content_type="application/json", artifact_metadata={})
    try:
        store = store or build_store()
        artifact.storage_backend = store.backend
        pack = build_evidence_pack(db, decision, trigger)
        data = json.dumps(pack, indent=2, sort_keys=True, default=str).encode("utf-8")
        key = f"{settings.artifacts_prefix.strip('/')}/{utcnow():%Y/%m/%d}/{decision.id}/{artifact.id}.json"
        obj = store.put(key, data, "application/json", {"decision-id": str(decision.id), "trigger": trigger})
        artifact.status, artifact.location, artifact.size_bytes, artifact.sha256 = "STORED", obj.key, obj.size_bytes, obj.sha256
        artifact.artifact_metadata = {"schema_version": PACK_SCHEMA_VERSION, "evidence_items": len(pack["evidence"]), "trace_entries": len(pack["agent_trace"])}
        emit({"EvidencePackStored": 1}, decision_id=decision.id)
        log_event(log, "artifact.stored", artifact_id=artifact.id, decision_id=decision.id, backend=store.backend, size_bytes=obj.size_bytes, sha256=obj.sha256)
    except StorageError as exc:
        artifact.status, artifact.error = "FAILED", str(exc)
    except Exception as exc:  # noqa: BLE001  (an audit copy must never take the approval down with it)
        artifact.status, artifact.error = "FAILED", f"evidence pack could not be built ({type(exc).__name__})"
    if artifact.status == "FAILED":
        emit({"EvidencePackFailed": 1}, decision_id=decision.id)
        log_event(log, "artifact.failed", level=40, artifact_id=artifact.id, decision_id=decision.id, backend=artifact.storage_backend, error=artifact.error)
    db.add(artifact)
    db.commit()
    return artifact


def list_for_decision(db: Session, decision_id: uuid.UUID) -> list[Artifact]:
    return list(db.scalars(select(Artifact).where(Artifact.decision_id == decision_id).order_by(Artifact.created_at)).all())


def read_artifact(artifact: Artifact, store: ArtifactStore | None = None) -> bytes:
    """Read the stored bytes and verify the SHA-256 recorded at write time."""
    if artifact.status != "STORED" or not artifact.location:
        raise StorageError("artifact was not stored")
    store = store or build_store(artifact.storage_backend)
    data = store.get(artifact.location)
    from app.storage.base import sha256_hex

    if sha256_hex(data) != artifact.sha256:
        raise StorageError("integrity check failed: stored bytes do not match the recorded SHA-256")
    return data
